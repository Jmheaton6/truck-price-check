"""Build lanes.js: the Findlay pilot lane price list the app reads.

Source: Detail sheet of the Ball logistics workbook, 2026 (Jan-Jul), shuttles excluded.
Spot is measured with SM Volume, never the carrier name.
Spot / contract cost per load use pure-spot (SM only) and pure-contract (contract only)
rows, so mixed rows don't blur the premium.

Usage: python -I scripts/build_seed.py <workbook.xlsx> <out lanes.js>
"""
import json
import sys
from collections import defaultdict

import openpyxl

ORIGIN = "FINDLAY, OH"
GROUPS = {"US SALES ORDER": "order", "US TRANSFER": "transfer"}
TOP_ORDERS, TOP_TRANSFERS = 8, 12
WEEKS_2026 = 212 / 7  # Jan 1 - Jul 31, 2026: the weeks the workbook covers


def build(path):
    ws = openpyxl.load_workbook(path, read_only=True)["Detail"]
    rows = ws.iter_rows(values_only=True)
    next(rows)
    lanes = defaultdict(lambda: dict(cv=0, sm=0, s_cost=0.0, s_n=0, c_cost=0.0, c_n=0, miles=None))
    check = dict(total=0, spot=0, over=0.0)
    for year, _m, group, lane, _car, cv, sm, _tv, _sp, dist, base, _prim, over, _pta in rows:
        if year != 2026 or "SHUTTLE" in str(group):
            continue
        cv, sm = cv or 0, sm or 0
        check["total"] += cv + sm
        check["spot"] += sm
        check["over"] += over if isinstance(over, (int, float)) else 0
        if group not in GROUPS or not str(lane).startswith(ORIGIN + " TO "):
            continue
        L = lanes[(GROUPS[group], lane)]
        L["cv"] += cv
        L["sm"] += sm
        if isinstance(dist, (int, float)):
            L["miles"] = dist
        if isinstance(base, (int, float)):
            if sm and not cv:
                L["s_cost"] += sm * base
                L["s_n"] += sm
            elif cv and not sm:
                L["c_cost"] += cv * base
                L["c_n"] += cv
    return lanes, check


def pick(lanes):
    out = []
    for kind, top in (("order", TOP_ORDERS), ("transfer", TOP_TRANSFERS)):
        cands = [
            (k, v) for k, v in lanes.items()
            if k[0] == kind and v["s_n"] >= 3 and v["c_n"] >= 10
        ]
        cands.sort(key=lambda kv: -(kv[1]["cv"] + kv[1]["sm"]))
        for (kind_, lane), v in cands[:top]:
            loads = v["cv"] + v["sm"]
            spot_cost = v["s_cost"] / v["s_n"]
            contract_cost = v["c_cost"] / v["c_n"]
            dest = lane.split(" TO ", 1)[1].title()
            dest = dest[:-2] + dest[-2:].upper()  # "Columbus, Oh" -> "Columbus, OH"
            out.append(dict(
                kind=kind_, origin="Findlay, OH", destination=dest,
                loads_2026=loads, spot_loads_2026=v["sm"],
                spot_share=round(v["sm"] / loads, 4),
                contract_loads_2026=v["cv"],
                # Proxy for the contract carrier's weekly commitment: loads it actually took.
                contract_per_week=max(1, round(v["cv"] / WEEKS_2026)),
                contract_cost=round(contract_cost),
                spot_premium=max(0, round(spot_cost - contract_cost)),
            ))
    return out


def to_js(picked):
    lines = ",\n".join("  " + json.dumps(p) for p in picked)
    return (
        "// Generated by scripts/build_seed.py from the Detail sheet (2026 Jan-Jul, no shuttles).\n"
        "// spot_share = SM loads / all loads. contract_cost and spot_premium are $ per load.\n"
        "// contract_per_week = 2026 contract loads / 30.3 weeks (what contract carriers took).\n"
        "export const LANES = [\n" + lines + "\n];\n"
    )


if __name__ == "__main__":
    lanes, check = build(sys.argv[1])
    picked = pick(lanes)
    with open(sys.argv[2], "w") as f:
        f.write(to_js(picked))
    print(f"2026 non-shuttle check: loads {check['total']:,}  spot {check['spot']:,}  overspend ${check['over']:,.0f}")
    print(f"{'kind':9}{'destination':22}{'loads':>7}{'spot%':>7}{'contract':>10}{'premium':>9}")
    for p in picked:
        print(f"{p['kind']:9}{p['destination']:22}{p['loads_2026']:>7}{p['spot_share']:>7.0%}"
              f"{p['contract_cost']:>10,}{p['spot_premium']:>9,}")
