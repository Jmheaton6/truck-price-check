"""Build lanes.js: the pilot plant's lane price list and routing guides the app reads.

Source: Detail sheet of the Ball logistics workbook, 2026 (Jan-Jul), shuttles excluded.
Spot is measured with SM Volume, never the carrier name.
Spot / contract cost per load use pure-spot (SM only) and pure-contract (contract only)
rows, so mixed rows don't blur the premium.

Usage: python -I scripts/build_lanes.py <workbook.xlsx> <out lanes.js> ["MONTICELLO, IN"]

Routing guide: each lane's top 3 contract carriers by 2026 contract loads (primary, backup 1, backup 2).
A carrier's weekly commitment = its 2026 contract loads on the lane / 30.3 weeks (what it actually took).
"""
import json
import sys
from collections import defaultdict

import openpyxl

ORIGIN = sys.argv[3] if len(sys.argv) > 3 else "MONTICELLO, IN"
GROUPS = {"US SALES ORDER": "order", "US TRANSFER": "transfer"}
TOP_ORDERS, TOP_TRANSFERS = 20, 20  # every lane with enough data to price
WEEKS_2026 = 212 / 7  # Jan 1 - Jul 31, 2026: the weeks the workbook covers


def build(path):
    ws = openpyxl.load_workbook(path, read_only=True)["Detail"]
    rows = ws.iter_rows(values_only=True)
    next(rows)
    lanes = defaultdict(lambda: dict(cv=0, sm=0, s_cost=0.0, s_n=0, c_cost=0.0, c_n=0, miles=None, carriers=defaultdict(int)))
    check = dict(total=0, spot=0, over=0.0)
    monthly = defaultdict(int)  # the plant's non-shuttle loads per month, 2024 to Jul 2026
    for year, ym, group, lane, car, cv, sm, _tv, _sp, dist, base, _prim, over, _pta in rows:
        if "SHUTTLE" in str(group):
            continue
        if str(lane).startswith(ORIGIN + " TO "):
            monthly[str(ym)] += (cv or 0) + (sm or 0)
        if year != 2026:
            continue
        cv, sm = cv or 0, sm or 0
        check["total"] += cv + sm
        check["spot"] += sm
        check["over"] += over if isinstance(over, (int, float)) else 0
        if group not in GROUPS or not str(lane).startswith(ORIGIN + " TO "):
            continue
        L = lanes[(GROUPS[group], lane)]
        L["cv"] += cv
        L["sm"] += sm
        # "SPOT FREIGHT" is a contract carrier's name, not spot; leave it out of the routing guide so no one is confused.
        if cv and str(car).strip().upper() != "SPOT FREIGHT":
            L["carriers"][str(car).strip()] += cv
        if isinstance(dist, (int, float)):
            L["miles"] = dist
        if isinstance(base, (int, float)):
            if sm and not cv:
                L["s_cost"] += sm * base
                L["s_n"] += sm
            elif cv and not sm:
                L["c_cost"] += cv * base
                L["c_n"] += cv
    return lanes, check, monthly


def pick(lanes):
    out = []
    for kind, top in (("order", TOP_ORDERS), ("transfer", TOP_TRANSFERS)):
        cands = [
            (k, v) for k, v in lanes.items()
            if k[0] == kind and v["s_n"] >= 3 and v["c_n"] >= 10
        ]
        cands.sort(key=lambda kv: -(kv[1]["cv"] + kv[1]["sm"]))
        for (kind_, lane), v in cands[:top]:
            loads = v["cv"] + v["sm"]
            spot_cost = v["s_cost"] / v["s_n"]
            contract_cost = v["c_cost"] / v["c_n"]
            dest = lane.split(" TO ", 1)[1].title()
            dest = dest[:-2] + dest[-2:].upper()  # "Columbus, Oh" -> "Columbus, OH"
            origin = ORIGIN.title()[:-2] + ORIGIN[-2:]
            top3 = [kv for kv in sorted(v["carriers"].items(), key=lambda kv: -kv[1]) if kv[1] / WEEKS_2026 >= 0.25][:3]
            out.append(dict(
                kind=kind_, origin=origin, destination=dest,
                miles=v["miles"],
                loads_2026=loads, spot_loads_2026=v["sm"],
                spot_share=round(v["sm"] / loads, 4),
                contract_loads_2026=v["cv"],
                # Proxy for the contract carrier's weekly commitment: loads it actually took.
                contract_per_week=max(1, round(v["cv"] / WEEKS_2026)),
                contract_cost=round(contract_cost),
                spot_premium=max(0, round(spot_cost - contract_cost)),
                carriers=[dict(name=n.title(), per_week=round(c / WEEKS_2026, 1)) for n, c in top3],
            ))
    return out


def to_js(picked, monthly):
    lines = ",\n".join("  " + json.dumps(p) for p in picked)
    import datetime
    months = sorted(monthly, key=lambda m: datetime.datetime.strptime(m, "%b-%Y"))
    return (
        "// Generated by scripts/build_lanes.py from the Detail sheet (2026 Jan-Jul, no shuttles).\n"
        "// spot_share = SM loads / all loads. contract_cost and spot_premium are $ per load.\n"
        "// contract_per_week = 2026 contract loads / 30.3 weeks (what contract carriers took).\n"
        "// carriers = the lane's routing guide: top 3 contract carriers, per_week = their 2026 contract loads / 30.3.\n"
        "export const LANES = [\n" + lines + "\n];\n"
        f"// The plant's non-shuttle loads per month (all lanes), for the long-term view.\n"
        "export const MONTHLY = " + json.dumps({m: monthly[m] for m in months}) + ";\n"
    )


if __name__ == "__main__":
    lanes, check, monthly = build(sys.argv[1])
    picked = pick(lanes)
    with open(sys.argv[2], "w") as f:
        f.write(to_js(picked, monthly))
    print(f"2026 non-shuttle check: loads {check['total']:,}  spot {check['spot']:,}  overspend ${check['over']:,.0f}")
    print(f"{'kind':9}{'destination':22}{'loads':>7}{'spot%':>7}{'contract':>10}{'premium':>9}")
    for p in picked:
        print(f"{p['kind']:9}{p['destination']:22}{p['loads_2026']:>7}{p['spot_share']:>7.0%}"
              f"{p['contract_cost']:>10,}{p['spot_premium']:>9,}  {p['miles']}mi  "
              + " | ".join(f"{c['name'][:18]} {c['per_week']}" for c in p["carriers"]))
